// Command gens3 generates s3/client_gen.go: one method on s3.Client for every
// operation the AWS SDK's S3 client defines. Each method takes the SDK input
// struct, fills in the Client's bucket when the input leaves it empty, and
// wraps errors with the operation name (object-level "not found" errors also
// match s3.ErrNotFound).
//
// Run it from the s3 directory after changing the SDK version:
//
//	go generate ./s3
//
// It inspects the SDK by reflection, so it needs no network. The completeness
// test in s3/client_test.go fails when the SDK gains an operation that has not
// been generated yet.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"reflect"
	"sort"
	"strings"

	awss3 "github.com/aws/aws-sdk-go-v2/service/s3"
)

// notes add a caveat to a generated method's documentation.
var notes = map[string]string{
	"GetObject":              "The caller must close the returned Body.",
	"GetObjectTorrent":       "The caller must close the returned Body.",
	"SelectObjectContent":    "The caller must close the returned event stream (out.GetStream().Close()).",
	"WriteGetObjectResponse": "This is for S3 Object Lambda functions and is only meaningful on AWS.",
}

// dangerous operations permanently remove or replace data or access rules.
func dangerous(op string) bool {
	return strings.HasPrefix(op, "Delete") ||
		op == "PutBucketPolicy" || op == "PutBucketAcl" || op == "PutObjectAcl" ||
		op == "PutPublicAccessBlock" || op == "PutBucketLifecycleConfiguration" ||
		op == "PutObjectLockConfiguration" || op == "PutObjectLegalHold" || op == "PutObjectRetention"
}

func main() {
	out := flag.String("out", "client_gen.go", "output file")
	flag.Parse()

	ct := reflect.TypeOf(&awss3.Client{})
	var ops []string
	for i := 0; i < ct.NumMethod(); i++ {
		m := ct.Method(i)
		if shape(m) {
			ops = append(ops, m.Name)
		}
	}
	sort.Strings(ops)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gens3; DO NOT EDIT.\n\npackage s3\n\n")
	b.WriteString("import (\n\t\"context\"\n\n\t\"github.com/aws/aws-sdk-go-v2/aws\"\n\tawss3 \"github.com/aws/aws-sdk-go-v2/service/s3\"\n)\n\n")
	b.WriteString("// generatedOperations lists every operation generated, for the completeness test.\n")
	b.WriteString("var generatedOperations = []string{\n")
	for _, op := range ops {
		fmt.Fprintf(&b, "\t%q,\n", op)
	}
	b.WriteString("}\n")

	for _, op := range ops {
		m, _ := ct.MethodByName(op)
		in := m.Type.In(2).Elem()
		hasBucket := false
		if f, ok := in.FieldByName("Bucket"); ok && f.Type == reflect.TypeOf((*string)(nil)) {
			hasBucket = true
		}
		fmt.Fprintf(&b, "\n// %s calls the S3 %s operation.", op, op)
		if hasBucket {
			b.WriteString(" An empty in.Bucket is replaced by the Client's bucket.")
		}
		b.WriteString(" The input is not modified.\n")
		if n := notes[op]; n != "" {
			fmt.Fprintf(&b, "//\n// %s\n", n)
		}
		if dangerous(op) {
			b.WriteString("//\n// Dangerous: this removes or replaces data or access rules.\n")
		}
		fmt.Fprintf(&b, "func (c *Client) %[1]s(ctx context.Context, in *awss3.%[1]sInput, optFns ...func(*awss3.Options)) (*awss3.%[1]sOutput, error) {\n", op)
		fmt.Fprintf(&b, "\tcp := awss3.%sInput{}\n\tif in != nil {\n\t\tcp = *in\n\t}\n", op)
		if hasBucket {
			b.WriteString("\tif cp.Bucket == nil || *cp.Bucket == \"\" {\n\t\tcp.Bucket = aws.String(c.Bucket)\n\t}\n")
		}
		fmt.Fprintf(&b, "\tout, err := c.S3.%s(ctx, &cp, optFns...)\n\tif err != nil {\n\t\treturn nil, opError(%q, err)\n\t}\n\treturn out, nil\n}\n", op, op)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("%d operations -> %s\n", len(ops), *out)
}

// shape reports whether m looks like an S3 operation:
// (ctx, *XInput, ...func(*Options)) (*XOutput, error).
func shape(m reflect.Method) bool {
	t := m.Type
	if m.Name == "Options" || t.NumIn() != 4 || t.NumOut() != 2 || !t.IsVariadic() {
		return false
	}
	in, out := t.In(2), t.Out(0)
	return in.Kind() == reflect.Ptr && out.Kind() == reflect.Ptr &&
		in.Elem().Name() == m.Name+"Input" && out.Elem().Name() == m.Name+"Output"
}
